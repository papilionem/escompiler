/// Create a Symbol with an optional description string.
///
/// The description argument is a NaN-boxed value: if it is a string, its text
/// is used as the symbol's description; if it is undefined (or any non-string),
/// the symbol has no description. Returns a NaN-boxed symbol value (not an
/// object wrapper) whose payload is the unique symbol ID.
///
/// Calling `new Symbol()` is a TypeError in JavaScript — the compiler should
/// prevent that; this function only handles the `Symbol(desc?)` call form.
#[unsafe(no_mangle)]
pub extern "C" fn __esc_rt_create_symbol(desc: u64) -> u64 {
    let desc_val = JsValue::from_raw_bits(desc);
    let description = if desc_val.is_string() {
        Some(crate::string_ops::get_string_data(desc_val))
    } else if desc_val.is_undefined() {
        None
    } else {
        // Non-string, non-undefined: coerce to string for description
        Some(crate::display::display_value(desc_val))
    };
    let id = crate::symbol::create_symbol(description.as_deref());
    JsValue::symbol(id).raw_bits()
}

/// `Symbol.for(key)` — look up or create a symbol in the global symbol registry.
///
/// If a symbol with the given string key already exists in the global registry,
/// returns it. Otherwise, creates a new symbol with the key as its description,
/// registers it, and returns it. The `key` argument is a NaN-boxed string.
#[unsafe(no_mangle)]
pub extern "C" fn __esc_rt_symbol_for(key: u64) -> u64 {
    let key_str = extract_key_string(key).unwrap_or_default();
    let id = crate::symbol::symbol_for(&key_str);
    JsValue::symbol(id).raw_bits()
}

/// `Symbol.keyFor(sym)` — reverse lookup: return the registry key for a symbol.
///
/// If the symbol was created via `Symbol.for(key)`, returns the key as a
/// NaN-boxed string. Otherwise, returns `undefined`.
#[unsafe(no_mangle)]
pub extern "C" fn __esc_rt_symbol_key_for(sym: u64) -> u64 {
    let val = JsValue::from_raw_bits(sym);
    let id = if let Some(id) = val.as_symbol() {
        id
    } else {
        return JsValue::undefined().raw_bits();
    };
    match crate::symbol::symbol_key_for(id) {
        Some(key) => make_rt_string(key),
        None => JsValue::undefined().raw_bits(),
    }
}

