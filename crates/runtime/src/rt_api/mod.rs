/// Create a closure object pairing a function index with an environment.
///
/// Creates a `UnifiedObject` with `InternalKind::Closure` and `ObjTag::Unified`,
/// storing the function index and captured environment in the internal data.
///
/// `flags` encodes:
/// - Bit 0: `is_arrow` (skip .prototype creation, lexical this)
/// - Bit 1: `is_strict` (sloppy this substitution check)
/// - Bit 2: `is_generator` (generator function)
///
/// Non-arrow functions also get a `.prototype` property with a `.constructor`
/// back-reference, matching JavaScript's behavior.
#[unsafe(no_mangle)]
pub extern "C" fn __esc_rt_create_closure(func_idx: u32, env: u64, flags: u32) -> u64 {
    let closure_bits = TaggedObj::boxed(
        ObjTag::Unified,
        crate::internal_data::UnifiedObject::closure(ShapeTable::EMPTY_SHAPE, func_idx, env, flags),
    );

    // Arrow functions do NOT get a .prototype property per the ES spec.
    let is_arrow = flags & 1 != 0;
    if !is_arrow {
        let proto = __esc_rt_create_object();
        let ctor_key = make_rt_string("constructor".to_string());
        __esc_rt_set_prop(proto, ctor_key, closure_bits);
        let proto_key = make_rt_string("prototype".to_string());
        __esc_rt_set_prop(closure_bits, proto_key, proto);
    }

    closure_bits
}

