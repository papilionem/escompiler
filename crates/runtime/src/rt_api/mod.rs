/// Object.defineProperty — delegates to the full Object.defineProperty
/// implementation which correctly parses descriptor flags (writable,
/// enumerable, configurable, value, get, set) per ES2024 §20.1.2.8.
///
/// ESC-5: Previously this was a stub that only read `value` from the
/// descriptor and called `__esc_rt_set_prop`, ignoring all descriptor flags.
/// Non-writable properties created via Object.defineProperty were stored as
/// writable, so sloppy assignment could silently overwrite them.
#[unsafe(no_mangle)]
pub extern "C" fn __esc_rt_object_define_property(obj: u64, key: u64, desc: u64) -> u64 {
    let argv: [u64; 3] = [obj, key, desc];
    dispatch_object_static_method("defineProperty", 3, argv.as_ptr());
    obj
}

