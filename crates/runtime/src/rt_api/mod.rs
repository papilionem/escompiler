/// Extract a numeric value from a [`JsValue`] for Math/Number operations.
///
/// Follows the JS `ToNumber` abstract operation (simplified).
pub(crate) fn val_to_f64(val: &JsValue) -> f64 {
    if let Some(n) = val.as_number() {
        n
    } else if let Some(n) = val.as_int() {
        n as f64
    } else if let Some(b) = val.as_bool() {
        if b { 1.0 } else { 0.0 }
    } else if val.is_null() {
        0.0
    } else if val.is_object() {
        // Try unwrapping wrapper objects (NumberObj, BooleanObj)
        let unwrapped = unwrap_wrapper_object(val.raw_bits());
        if unwrapped != val.raw_bits() {
            return val_to_f64(&JsValue::from_raw_bits(unwrapped));
        }
        f64::NAN
    } else {
        f64::NAN
    }
}

/// If `bits` is a wrapper object (BooleanObj/NumberObj/StringObj), return the
/// wrapped primitive value. Otherwise return the original bits unchanged.
///
/// Used by builtin dispatch methods that receive `this` as a wrapper object
/// (e.g., `new Boolean(true).valueOf()` receives the BooleanObj as `this`
/// and needs to unwrap it to the boolean `true`).
pub(crate) fn unwrap_wrapper_object(bits: u64) -> u64 {
    let tag = read_obj_tag(bits);
    if tag != Some(ObjTag::Unified as u8) {
        return bits;
    }
    let uni = unsafe {
        // SAFETY: tag check confirms this is a unified object.
        deref_tagged::<crate::internal_data::UnifiedObject>(bits)
    };
    let Some(u) = uni else { return bits };
    match u.kind {
        crate::internal_data::InternalKind::BooleanObj => {
            if let Some(crate::internal_data::InternalData::BooleanWrapper { value }) =
                u.internal_data()
            {
                return *value;
            }
        }
        crate::internal_data::InternalKind::NumberObj => {
            if let Some(crate::internal_data::InternalData::NumberWrapper { value }) =
                u.internal_data()
            {
                return *value;
            }
        }
        crate::internal_data::InternalKind::StringObj => {
            if let Some(crate::internal_data::InternalData::StringWrapper { value }) =
                u.internal_data()
            {
                return *value;
            }
        }
        _ => {}
    }
    bits
}

