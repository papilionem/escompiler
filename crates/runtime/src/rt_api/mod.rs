/// Create a closure environment with `slot_count` slots and a parent pointer.
///
/// `parent` is a NaN-boxed object pointer to the parent environment, or
/// 0 / undefined for top-level.
#[unsafe(no_mangle)]
pub extern "C" fn __esc_rt_env_create(parent: u64, slot_count: u32) -> u64 {
    let parent_ptr = if parent == 0 || parent == JsValue::undefined().raw_bits() {
        std::ptr::null_mut()
    } else {
        let v = JsValue::from_raw_bits(parent);
        v.as_object().unwrap_or(std::ptr::null()) as *mut Environment
    };
    let env = Box::new(Environment::new(slot_count, parent_ptr));
    let ptr = Box::into_raw(env) as *const ();
    JsValue::object(ptr).raw_bits()
}

/// Load a value from a closure environment at (depth, slot).
#[unsafe(no_mangle)]
pub extern "C" fn __esc_rt_env_load(env: u64, depth: u32, slot: u32) -> u64 {
    let v = JsValue::from_raw_bits(env);
    let Some(ptr) = v.as_object() else {
        return JsValue::undefined().raw_bits();
    };
    if ptr.is_null() {
        return JsValue::undefined().raw_bits();
    }
    let environment = unsafe {
        // SAFETY: ptr was created by __esc_rt_env_create via Box::into_raw.
        &*(ptr as *const Environment)
    };
    environment.load(depth, slot)
}

/// Store a value into a closure environment at (depth, slot).
#[unsafe(no_mangle)]
pub extern "C" fn __esc_rt_env_store(env: u64, depth: u32, slot: u32, val: u64) {
    let v = JsValue::from_raw_bits(env);
    let Some(ptr) = v.as_object() else {
        return;
    };
    if ptr.is_null() {
        return;
    }
    let environment = unsafe {
        // SAFETY: ptr was created by __esc_rt_env_create via Box::into_raw.
        &mut *(ptr as *mut Environment)
    };
    environment.store(depth, slot, val);
}

