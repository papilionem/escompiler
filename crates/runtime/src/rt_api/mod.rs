/// Create a new empty JS object and return it as a NaN-boxed object value.
///
/// Allocates a [`UnifiedObject`](crate::internal_data::UnifiedObject) with
/// an empty shape and inline property storage.
#[unsafe(no_mangle)]
pub extern "C" fn __esc_rt_create_object() -> u64 {
    let obj = crate::internal_data::UnifiedObject::ordinary(ShapeTable::EMPTY_SHAPE);
    let bits = TaggedObj::boxed(ObjTag::Unified, obj);

    // Per ES2024 §10.1: Ordinary objects have [[Prototype]] = Object.prototype.
    // Only set in non-test builds (tests don't link __esc_dispatch).
    #[cfg(not(test))]
    {
        thread_local! {
            static CACHED_OBJ_PROTO: std::cell::Cell<u64> = const { std::cell::Cell::new(0) };
            static INITIALIZING: std::cell::Cell<bool> = const { std::cell::Cell::new(false) };
        }

        let cached = CACHED_OBJ_PROTO.with(|c| c.get());
        if cached != 0 {
            dispatch_core::set_prototype_on_new_object(bits, cached);
        } else if !INITIALIZING.with(|c| c.get()) {
            INITIALIZING.with(|c| c.set(true));
            let obj_proto = get_or_create_builtin_prototype("Object");
            CACHED_OBJ_PROTO.with(|c| c.set(obj_proto));
            dispatch_core::set_prototype_on_new_object(bits, obj_proto);
            INITIALIZING.with(|c| c.set(false));
        }
    }

    bits
}

/// Create an object from an interleaved key-value array.
///
/// `count` is the number of key-value **pairs** (not the total array length).
/// `kvpairs` is a pointer to an array of `2 * count` NaN-boxed `u64` values
/// laid out as `[key0, val0, key1, val1, ...]`. Keys are NaN-boxed strings.
///
/// On first call with a unique key sequence, builds the shape chain from
/// the empty shape by adding each key in order and caches the resulting
/// `ShapeId`. Subsequent calls with the same key sequence skip all shape
/// transitions and create the object directly with the cached shape.
///
/// # Safety
///
/// `kvpairs` must point to a valid array of at least `2 * count` `u64` values.
#[unsafe(no_mangle)]
pub unsafe extern "C" fn __esc_rt_create_object_literal(count: u32, kvpairs: u64) -> u64 {
    let pair_count = count as usize;
    let ptr = kvpairs as *const u64;

    // SAFETY: Caller (compiled code) guarantees `ptr` points to `2 * count` u64 values.
    let slice = unsafe { std::slice::from_raw_parts(ptr, pair_count * 2) };

    // Intern key strings and collect their raw atom IDs for cache lookup
    let atom_raws: Vec<u32> = (0..pair_count)
        .map(|i| {
            let key_bits = slice[i * 2];
            let key_str = key_to_string(key_bits);
            INTERNER.with(|interner| interner.borrow().intern(&key_str).into_raw())
        })
        .collect();

    // Look up or build the shape chain
    let shape_id = LITERAL_SHAPE_CACHE.with(|cache| {
        let cache_ref = cache.borrow();
        if let Some(&cached) = cache_ref.get(&atom_raws) {
            return cached;
        }
        drop(cache_ref);

        // Build shape chain from empty
        let final_shape = SHAPES.with(|shapes| {
            let mut shapes = shapes.borrow_mut();
            let mut shape = ShapeTable::EMPTY_SHAPE;
            for &raw in &atom_raws {
                let atom = interner::Atom::from_raw(raw);
                shape = shapes.add_property(shape, atom);
            }
            shape
        });

        cache.borrow_mut().insert(atom_raws, final_shape);
        final_shape
    });

    // Create object with the final shape and pre-fill slots
    let mut obj = crate::internal_data::UnifiedObject::ordinary(shape_id);
    obj.slots.reserve(pair_count);
    for i in 0..pair_count {
        let val_bits = slice[i * 2 + 1];
        obj.slots.push(JsValue::from_raw_bits(val_bits));
    }
    let bits = TaggedObj::boxed(ObjTag::Unified, obj);

    // Set Object.prototype (same as __esc_rt_create_object)
    #[cfg(not(test))]
    {
        thread_local! {
            static CACHED_OBJ_PROTO_LIT: std::cell::Cell<u64> = const { std::cell::Cell::new(0) };
            static INIT_LIT: std::cell::Cell<bool> = const { std::cell::Cell::new(false) };
        }
        let cached = CACHED_OBJ_PROTO_LIT.with(|c| c.get());
        if cached != 0 {
            dispatch_core::set_prototype_on_new_object(bits, cached);
        } else if !INIT_LIT.with(|c| c.get()) {
            INIT_LIT.with(|c| c.set(true));
            let obj_proto = get_or_create_builtin_prototype("Object");
            CACHED_OBJ_PROTO_LIT.with(|c| c.set(obj_proto));
            dispatch_core::set_prototype_on_new_object(bits, obj_proto);
            INIT_LIT.with(|c| c.set(false));
        }
    }

    bits
}

