/// `ToBoolean` returning a NaN-boxed boolean (not i1).
///
/// Used by backends that cannot handle the i1 return of `__esc_rt_to_boolean`.
#[unsafe(no_mangle)]
pub extern "C" fn __esc_rt_to_boolean_js(val: u64) -> u64 {
    let result = __esc_rt_to_boolean(val);
    if result != 0 {
        JsValue::bool(true).raw_bits()
    } else {
        JsValue::bool(false).raw_bits()
    }
}

/// `yield*` delegation — advances an inner iterator and returns the value.
///
/// Takes the iterator object and a value to pass via `.next()`.
/// Returns the iterator result object `{value, done}`.
#[unsafe(no_mangle)]
pub extern "C" fn __esc_rt_yield_delegate(iter: u64, value: u64) -> u64 {
    // Call iter.next(value) and return the result
    let next_key = make_rt_string("next".to_string());
    let next_fn = __esc_rt_get_prop(iter, next_key);
    let next_val = JsValue::from_raw_bits(next_fn);
    if next_val.is_undefined() || next_val.is_null() {
        // Iterator has no .next method — return {value: undefined, done: true}
        return __esc_rt_create_iter_result(
            JsValue::undefined().raw_bits(),
            JsValue::bool(true).raw_bits(),
        );
    }
    // Call .next(value) on the iterator
    let argv = [value];
    // SAFETY: argv is a valid array of 1 element on the stack.
    unsafe {
        dispatch_core::__esc_rt_call_method(
            iter,
            make_rt_string("next".to_string()),
            1,
            argv.as_ptr(),
        )
    }
}

