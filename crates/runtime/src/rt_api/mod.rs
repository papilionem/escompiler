/// An error object storing its type tag, raw message, formatted message, and stack trace.
pub struct JsError {
    /// Error type tag (0=Error, 1=TypeError, 2=RangeError, 3=ReferenceError, 4=SyntaxError).
    pub error_tag: u32,
    /// The full error message including prefix (e.g., "TypeError: Cannot read properties of null").
    pub message: u64,
    /// The raw message without the error type prefix (e.g., "Cannot read properties of null").
    pub raw_message: u64,
    /// The stack trace as a NaN-boxed string (e.g., "TypeError: msg\n    at <compiled>").
    pub stack: u64,
}

/// Create an Error object with the given tag and message.
///
/// Tags: 0=Error, 1=TypeError, 2=RangeError, 3=ReferenceError, 4=SyntaxError.
/// Stores the raw message, full formatted message (with error type prefix),
/// and a basic stack trace string.
#[unsafe(no_mangle)]
pub extern "C" fn __esc_rt_create_error(tag: u32, msg: u64) -> u64 {
    let msg_str = string_ops::get_string_data(JsValue::from_raw_bits(msg));
    let error_name = exceptions::error_name(tag);
    let full_msg = format!("{error_name}: {msg_str}");
    let stack_str = format!("{full_msg}\n    at <compiled>");
    let message = make_rt_string(full_msg);
    let raw_message = make_rt_string(msg_str);
    let stack = make_rt_string(stack_str);
    let error = crate::internal_data::UnifiedObject::error(
        ShapeTable::EMPTY_SHAPE,
        tag,
        message,
        raw_message,
        stack,
    );
    let bits = TaggedObj::boxed(ObjTag::Unified, error);

    // Set [[Prototype]] to the appropriate error constructor's prototype.
    // Per ES2024 §20.5.1: new Error() → OrdinaryCreateFromConstructor(Error, Error.prototype).
    let proto = get_or_create_builtin_prototype(error_name);
    dispatch_core::set_prototype_on_new_object(bits, proto);

    bits
}

