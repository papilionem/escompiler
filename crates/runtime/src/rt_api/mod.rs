/// Extract the property name string from a NaN-boxed key value.
///
/// For objects, applies `ToPrimitive(hint: String)` before converting to a
/// display string, matching the ECMAScript `ToPropertyKey` semantics.
pub(crate) fn key_to_string(key: u64) -> String {
    let v = JsValue::from_raw_bits(key);
    if v.is_string() {
        string_ops::get_string_data(v)
    } else if let Some(n) = v.as_int() {
        n.to_string()
    } else if v.is_symbol() {
        // Symbol keys are stored as their string representation
        // (e.g., "Symbol(Symbol.iterator)") for OBJECT_PROPS lookup.
        let id = v.as_symbol().unwrap_or(0);
        crate::symbol::symbol_to_string(id)
    } else if v.is_object() {
        // ToPrimitive with String hint, then display
        let prim = value_ops::to_primitive(v, value_ops::ToPrimitiveHint::String);
        display::display_value(prim)
    } else {
        display::display_value(v)
    }
}

/// Walk the prototype chain of an object looking for a property.
///
/// First checks the object's own properties (via shape-based slots), then
/// checks the OBJECT_PROPS side-table (for functions/closures), then follows
/// the prototype chain via shape-based prototype walking or legacy `__proto__`
/// property up to a maximum depth of 100 to prevent infinite loops.
///
/// **Note:** This function returns the raw slot value. For accessor properties
/// (getters), the raw getter function object is returned, NOT the getter's
/// return value. Use [`lookup_property_chain_get`] when you need accessor
/// invocation (i.e., for the `[[Get]]` internal method).
pub(crate) fn lookup_property_chain(obj: u64, name: &str) -> u64 {
    let mut current = obj;
    // Max 100 prototype hops to prevent infinite loops
    for _ in 0..100 {
        let tag = read_obj_tag(current);
        if tag != Some(ObjTag::Unified as u8) {
            break;
        }
        let uni = unsafe {
            // SAFETY: tag check confirms this is a unified object.
            deref_tagged::<crate::internal_data::UnifiedObject>(current)
        };
        let Some(u) = uni else { break };

        // 1. Check own properties via shape-based slot lookup
        let found = SHAPES.with(|shapes| {
            INTERNER.with(|interner| {
                let shapes = shapes.borrow();
                let interner = interner.borrow();
                u.get_slot_by_name(name, &shapes, &interner)
            })
        });
        if let Some(val) = found {
            return val.raw_bits();
        }

        // 2. Check OBJECT_PROPS side-table (for functions/closures)
        let side_table_val = OBJECT_PROPS.with(|props| {
            let props = props.borrow();
            props.get(&current).and_then(|m| m.get(name).copied())
        });
        if let Some(val) = side_table_val {
            return val;
        }

        // 3. Follow prototype chain
        match get_prototype_object(u) {
            Some(proto_bits) => current = proto_bits,
            None => break,
        }
    }
    JsValue::undefined().raw_bits()
}

/// Walk the prototype chain to check if a property EXISTS anywhere in the chain.
///
/// Unlike [`lookup_property_chain`], this uses `has_own_property` at each level,
/// so it correctly returns `true` for accessor properties with no getter
/// (where the value is `undefined` but the property DOES exist).
/// Also checks OBJECT_PROPS (side-table for functions/native constructors).
///
/// This is the correct implementation of `[[HasProperty]]` (OrdinaryHasProperty)
/// per ES2024 §10.1.7.
pub(crate) fn has_property_in_chain(obj: u64, name: &str) -> bool {
    let mut current = obj;
    // Max 100 prototype hops to prevent infinite loops
    for _ in 0..100 {
        let tag = read_obj_tag(current);
        if tag != Some(ObjTag::Unified as u8) {
            break;
        }
        let uni = unsafe {
            // SAFETY: tag check confirms this is a unified object.
            deref_tagged::<crate::internal_data::UnifiedObject>(current)
        };
        let Some(u) = uni else { break };

        // 1. Check own properties via shape-based has_own_property (handles both data
        //    and accessor properties correctly, unlike get_slot which returns undefined
        //    for accessor-with-no-getter).
        let has_own = SHAPES.with(|shapes| {
            INTERNER.with(|interner| {
                let shapes = shapes.borrow();
                let interner = interner.borrow();
                u.has_own_property(name, &shapes, &interner)
            })
        });
        if has_own {
            return true;
        }

        // 2. Check OBJECT_PROPS side-table (for functions/closures/NativeFunc)
        let in_side_table = OBJECT_PROPS.with(|props| {
            props
                .borrow()
                .get(&current)
                .is_some_and(|m| m.contains_key(name))
        });
        if in_side_table {
            return true;
        }

        // 3. Follow prototype chain
        match get_prototype_object(u) {
            Some(proto_bits) => current = proto_bits,
            None => break,
        }
    }
    false
}

/// Walk the prototype chain looking for a property, invoking accessor getters.
///
/// Like [`lookup_property_chain`], but implements the full `[[Get]]` semantics:
/// when a property found on the chain is an accessor (getter), the getter is
/// invoked with `receiver` as the `this` value and the getter's return value is
/// returned — not the raw getter function object.
///
/// `receiver` is the original object on which the property access was initiated
/// (ES2024 §10.1.8 OrdinaryGet, step 2c: `parent.[[Get]](P, Receiver)`).
pub(crate) fn lookup_property_chain_get(obj: u64, name: &str, receiver: u64) -> u64 {
    let mut current = obj;
    // Max 100 prototype hops to prevent infinite loops
    for _ in 0..100 {
        let tag = read_obj_tag(current);
        if tag != Some(ObjTag::Unified as u8) {
            break;
        }
        let uni = unsafe {
            // SAFETY: tag check confirms this is a unified object.
            deref_tagged::<crate::internal_data::UnifiedObject>(current)
        };
        let Some(u) = uni else { break };

        // 1. Check own properties — first check for accessor properties
        let accessor_result = SHAPES.with(|shapes| {
            INTERNER.with(|interner| {
                let shapes = shapes.borrow();
                let interner = interner.borrow();
                // Check if this is an accessor property
                if let Some(getter) = u.get_accessor_getter(name, &shapes, &interner) {
                    // §10.1.8 step 4: IsAccessorDescriptor(desc) is true
                    if !getter.is_undefined() {
                        // §10.1.8 step 4c: Return ? Call(getter, Receiver).
                        Some(Some(getter))
                    } else {
                        // §10.1.8 step 4b: getter is undefined, return undefined.
                        Some(None)
                    }
                } else {
                    // Not an accessor — check for data property
                    None
                }
            })
        });
        match accessor_result {
            Some(Some(getter)) => {
                // Invoke the getter with the original receiver as `this`
                let prev_this = CURRENT_THIS.with(|cell| cell.replace(receiver));
                let result = unsafe {
                    // SAFETY: getter was found by shape-based accessor lookup.
                    __esc_rt_call_indirect(getter.raw_bits(), 0, std::ptr::null())
                };
                CURRENT_THIS.with(|cell| cell.set(prev_this));
                return result;
            }
            Some(None) => {
                // Accessor exists but no getter: return undefined
                return JsValue::undefined().raw_bits();
            }
            None => {
                // Not an accessor — check for data property via slot lookup
            }
        }

        // 1b. Check own data properties via shape-based slot lookup
        let found = SHAPES.with(|shapes| {
            INTERNER.with(|interner| {
                let shapes = shapes.borrow();
                let interner = interner.borrow();
                u.get_slot_by_name(name, &shapes, &interner)
            })
        });
        if let Some(val) = found {
            return val.raw_bits();
        }

        // 2. Check OBJECT_PROPS side-table (for functions/closures)
        let side_table_val = OBJECT_PROPS.with(|props| {
            let props = props.borrow();
            props.get(&current).and_then(|m| m.get(name).copied())
        });
        if let Some(val) = side_table_val {
            return val;
        }

        // 3. Follow prototype chain
        match get_prototype_object(u) {
            Some(proto_bits) => current = proto_bits,
            None => break,
        }
    }
    JsValue::undefined().raw_bits()
}

/// Walk the prototype chain looking for an inherited accessor setter.
///
/// Similar to [`lookup_property_chain_get`] but for the `[[Set]]` path:
/// walks the prototype chain starting from `obj`'s prototype (skipping `obj`
/// itself, since own-property accessor setters are checked by the caller).
///
/// Returns `Some(setter_value)` if an accessor property is found on the chain
/// (the setter may be `undefined` if no setter was defined). Returns `None`
/// if no accessor property is found on the chain (data or missing).
///
/// ES2024 §10.1.9 OrdinarySet, step 2: if ownDesc is undefined, delegate to
/// parent.[[Set]](P, V, Receiver).
pub(crate) fn lookup_proto_chain_setter(obj: u64, name: &str) -> Option<JsValue> {
    // Start from the first prototype (skip own object — caller already checked own)
    let tag = read_obj_tag(obj);
    if tag != Some(ObjTag::Unified as u8) {
        return None;
    }
    let uni = unsafe {
        // SAFETY: tag check confirms this is a unified object.
        deref_tagged::<crate::internal_data::UnifiedObject>(obj)
    };
    let u = uni?;
    let mut current = get_prototype_object(u)?;

    for _ in 0..100 {
        let tag = read_obj_tag(current);
        if tag != Some(ObjTag::Unified as u8) {
            break;
        }
        let uni = unsafe {
            // SAFETY: tag check confirms this is a unified object.
            deref_tagged::<crate::internal_data::UnifiedObject>(current)
        };
        let Some(cu) = uni else { break };

        // Check if this prototype has an accessor property with this name
        let accessor_setter = SHAPES.with(|shapes| {
            INTERNER.with(|interner| {
                let shapes = shapes.borrow();
                let interner = interner.borrow();
                cu.get_accessor_setter(name, &shapes, &interner)
            })
        });
        if let Some(setter) = accessor_setter {
            return Some(setter);
        }

        // Also check if this prototype has a data property (stop the walk)
        let has_data = SHAPES.with(|shapes| {
            INTERNER.with(|interner| {
                let shapes = shapes.borrow();
                let interner = interner.borrow();
                cu.has_own_property(name, &shapes, &interner)
            })
        });
        if has_data {
            // Data property found on prototype — no accessor setter to invoke
            return None;
        }

        match get_prototype_object(cu) {
            Some(proto_bits) => current = proto_bits,
            None => break,
        }
    }
    None
}

/// Get the prototype object for a unified object.
///
/// Uses a dual mechanism:
///   1. Shape-based prototype (via PROTO_OBJECTS registry)
///   2. Legacy `__proto__` string property stored on the object itself
///
/// Returns `Some(proto_bits)` if a prototype is found, `None` if no prototype.
pub(super) fn get_prototype_object(u: &crate::internal_data::UnifiedObject) -> Option<u64> {
    // 1. Check shape-based prototype (via PROTO_OBJECTS registry)
    let has_shape_proto = SHAPES.with(|shapes| {
        let shapes = shapes.borrow();
        shapes.get_prototype(u.shape_id)
    });
    if let Some(proto_shape_id) = has_shape_proto {
        let proto_bits = PROTO_OBJECTS.with(|protos| protos.borrow().get(&proto_shape_id).copied());
        if let Some(bits) = proto_bits {
            let val = JsValue::from_raw_bits(bits);
            if val.is_object() {
                return Some(bits);
            }
            // Explicitly null prototype (e.g., Object.create(null)) — no prototype.
            if val.is_null() {
                return None;
            }
        }
    }

    // 2. Legacy: check __proto__ string property on the object
    if matches!(u.kind, crate::internal_data::InternalKind::Ordinary) {
        let proto = SHAPES.with(|shapes| {
            INTERNER.with(|interner| {
                let shapes = shapes.borrow();
                let interner = interner.borrow();
                u.get_slot_by_name("__proto__", &shapes, &interner)
            })
        });
        if let Some(p) = proto
            && p.is_object()
        {
            return Some(p.raw_bits());
        }
    }

    // 3. Implicit prototype fallback based on object kind.
    // Per ES2024, every object has an implicit [[Prototype]] link to its
    // constructor's prototype. We return the builtin prototype lazily.
    // Guard against recursion (prototype creation calls back here) via a
    // thread-local re-entrancy flag.
    thread_local! {
        static IN_PROTO_LOOKUP: std::cell::Cell<bool> = const { std::cell::Cell::new(false) };
    }
    if IN_PROTO_LOOKUP.with(|f| f.get()) {
        return None;
    }
    let builtin_name = implicit_prototype_name(u.kind);
    if let Some(name) = builtin_name {
        IN_PROTO_LOOKUP.with(|f| f.set(true));
        let proto = crate::rt_api::property::get_or_create_builtin_prototype(name);
        IN_PROTO_LOOKUP.with(|f| f.set(false));
        if proto != 0 {
            let v = JsValue::from_raw_bits(proto);
            if v.is_object() {
                return Some(proto);
            }
        }
    }
    None
}

/// Map an `InternalKind` to the name of its implicit builtin prototype.
///
/// Returns `None` for kinds that have no implicit builtin prototype
/// (e.g., `Ordinary` which uses Object.prototype only when explicitly linked).
fn implicit_prototype_name(kind: crate::internal_data::InternalKind) -> Option<&'static str> {
    use crate::internal_data::InternalKind;
    match kind {
        InternalKind::Function | InternalKind::Closure | InternalKind::NativeFunc => {
            Some("Function")
        }
        InternalKind::Array => Some("Array"),
        InternalKind::RegExpObj => Some("RegExp"),
        InternalKind::DateObj => Some("Date"),
        InternalKind::MapObj => Some("Map"),
        InternalKind::SetObj => Some("Set"),
        InternalKind::WeakMapObj => Some("WeakMap"),
        InternalKind::WeakSetObj => Some("WeakSet"),
        InternalKind::WeakRefObj => Some("WeakRef"),
        InternalKind::BooleanObj => Some("Boolean"),
        InternalKind::NumberObj => Some("Number"),
        InternalKind::StringObj => Some("String"),
        InternalKind::ErrorObj => Some("Error"),
        InternalKind::Generator => Some("GeneratorFunction"),
        // IterResult, Promise, Symbol, Iterator, etc. don't have a simple prototype
        _ => None,
    }
}

/// Extract a non-negative integer index from a NaN-boxed key.
///
/// Handles both `JsValue::int` (tagged i32) and `JsValue::number` (f64 that
/// is an exact non-negative integer).
pub(crate) fn as_array_index(kv: JsValue) -> Option<u32> {
    if let Some(i) = kv.as_int() {
        if i >= 0 {
            return Some(i as u32);
        }
    } else if let Some(n) = kv.as_number() {
        let idx = n as u32;
        if (idx as f64) == n {
            return Some(idx);
        }
    }
    None
}

/// Extract a string from a NaN-boxed key value.
pub(crate) fn extract_key_string(key: u64) -> Option<String> {
    let v = JsValue::from_raw_bits(key);
    if let Some(ptr) = v.as_string() {
        if ptr.is_null() {
            return Some(String::new());
        }
        let rt_str = unsafe {
            // SAFETY: string pointers are created by __esc_rt_string_from_data
            // via Box::into_raw on RtString.
            &*(ptr as *const string_ops::RtString)
        };
        Some(rt_str.as_str().to_owned())
    } else {
        v.as_int().map(|n| n.to_string())
    }
}

/// Read argv into a `Vec<JsValue>`.
pub(crate) fn read_argv(argc: u32, argv: *const u64) -> Vec<JsValue> {
    if argv.is_null() || argc == 0 {
        return Vec::new();
    }
    let mut args = Vec::with_capacity(argc as usize);
    for i in 0..argc as usize {
        let bits = unsafe {
            // SAFETY: caller guarantees argv points to argc valid u64 values.
            *argv.add(i)
        };
        args.push(JsValue::from_raw_bits(bits));
    }
    args
}

/// Format a JsValue for array join (similar to display but simpler).
///
/// Null and undefined format as empty strings per the spec.
pub(crate) fn format_value_for_join(v: JsValue) -> String {
    if v.is_undefined() || v.is_null() {
        return String::new();
    }
    if let Some(n) = v.as_int() {
        return n.to_string();
    }
    if let Some(n) = v.as_number() {
        if n == n.trunc() && n.abs() < 1e15 {
            return format!("{}", n as i64);
        }
        return format!("{n}");
    }
    if let Some(b) = v.as_bool() {
        return b.to_string();
    }
    if let Some(ptr) = v.as_string()
        && !ptr.is_null()
    {
        let rt_str = unsafe {
            // SAFETY: string pointer created by runtime string allocation.
            &*(ptr as *const string_ops::RtString)
        };
        return rt_str.as_str().to_string();
    }
    String::new()
}

/// Create a NaN-boxed string from a Rust `String`.
pub fn make_rt_string(s: String) -> u64 {
    let rt_str = Box::new(string_ops::RtString::new(s));
    let ptr = Box::into_raw(rt_str) as *const ();
    JsValue::string(ptr).raw_bits()
}

/// Normalize a JS-style index (negative means from end).
pub(crate) fn normalize_index(idx: i32, len: i32) -> usize {
    if idx < 0 {
        (len + idx).max(0) as usize
    } else {
        idx.min(len) as usize
    }
}

/// Compare two JS values for sorting (default string comparison per spec).
pub(crate) fn compare_js_values(a: JsValue, b: JsValue) -> std::cmp::Ordering {
    let a_str = format_value_for_join(a);
    let b_str = format_value_for_join(b);
    a_str.cmp(&b_str)
}

