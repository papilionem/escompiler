/// Create an arguments object from the current function's arguments.
///
/// Reads the current call's `CURRENT_ARGC` and `CURRENT_ARGV` thread-locals
/// to populate an ordinary object (NOT an array) with indexed properties and
/// a `.length` property. In sloppy mode, also sets `.callee` to the current
/// closure value from `CURRENT_CALLEE`.
///
/// Per ECMA-262 Section 10.4.4, the `arguments` object is an ordinary object
/// with `Object.prototype` as its prototype — it is NOT an Array.
#[unsafe(no_mangle)]
pub extern "C" fn __esc_rt_create_arguments() -> u64 {
    let argc = CURRENT_ARGC.with(|cell| cell.get()) as usize;
    let argv = CURRENT_ARGV.with(|cell| cell.get());
    let callee_bits = CURRENT_CALLEE.with(|cell| cell.get());

    // Build the arguments object as an ordinary object with indexed props + length
    create_arguments_object(argc, argv, callee_bits, false)
}

/// Create an arguments object with explicit strict-mode flag.
///
/// When `is_strict` is true, `.callee` is NOT set (accessing it would throw
/// TypeError in a full implementation; for now we omit it so that it returns
/// `undefined` which is closer to spec than returning the function).
///
/// When `is_strict` is false (sloppy mode), `.callee` is set to `callee_bits`.
fn create_arguments_object(
    argc: usize,
    argv: *const u64,
    callee_bits: u64,
    is_strict: bool,
) -> u64 {
    // Create an ordinary object (NOT an array)
    let obj_bits = __esc_rt_create_object();

    // Set indexed properties 0..argc-1
    for i in 0..argc {
        let val_bits = if !argv.is_null() {
            // SAFETY: argv points to argc valid u64 values, set by the
            // dispatch caller (same contract as __esc_rt_rest_args).
            unsafe { *argv.add(i) }
        } else {
            JsValue::undefined().raw_bits()
        };
        let key = JsValue::int(i as i32).raw_bits();
        __esc_rt_set_prop(obj_bits, key, val_bits);
    }

    // Set .length = argc
    let length_key = make_rt_string("length".to_string());
    let length_val = JsValue::int(argc as i32).raw_bits();
    __esc_rt_set_prop(obj_bits, length_key, length_val);

    // Set .callee in sloppy mode
    if !is_strict && callee_bits != 0 {
        let callee_key = make_rt_string("callee".to_string());
        __esc_rt_set_prop(obj_bits, callee_key, callee_bits);
    }

    obj_bits
}

