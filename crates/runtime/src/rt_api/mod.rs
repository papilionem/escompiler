/// Global runtime instance, initialized by `__esc_rt_init` and torn down
/// by `__esc_rt_shutdown`.
static mut GLOBAL_RUNTIME: Option<Box<Runtime>> = None;

/// Initialize the global runtime. Must be called once at program start
/// before any other `__esc_rt_*` functions.
///
/// # Safety
///
/// Must be called exactly once, before any concurrent access to the runtime.
#[unsafe(no_mangle)]
pub extern "C" fn __esc_rt_init() {
    unsafe {
        // SAFETY: Called once at program start before any other runtime functions.
        GLOBAL_RUNTIME = Some(Box::new(Runtime::new(false)));
    }
    // Set CURRENT_THIS to globalThis so that sloppy-mode top-level code
    // sees the global object as `this` (ES2024 §16.1.6 ScriptEvaluation step 3).
    let global = __esc_rt_get_global_this();
    CURRENT_THIS.with(|cell| cell.set(global));
}

/// Shut down the global runtime and release all resources.
///
/// Also resets timer state and drains remaining microtasks.
///
/// # Safety
///
/// Must be called exactly once, after all other `__esc_rt_*` calls have completed.
#[unsafe(no_mangle)]
pub extern "C" fn __esc_rt_shutdown() {
    // Drain any remaining microtasks
    promise::drain_microtasks();
    // Reset timer state
    timer::reset();
    unsafe {
        // SAFETY: Called once at program end after all other runtime functions.
        GLOBAL_RUNTIME = None;
    }
}

