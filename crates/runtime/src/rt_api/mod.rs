/// Native function implementing `[Symbol.iterator]() { return this; }`.
///
/// Reads the current `this` value from the thread-local `CURRENT_THIS` cell
/// and returns it. Used by generators and other iterators to satisfy the
/// iterable protocol: `g[Symbol.iterator]() === g`.
fn native_return_this(_context: u64) -> u64 {
    CURRENT_THIS.with(|cell| {
        let v = cell.get();
        if v == 0 {
            JsValue::undefined().raw_bits()
        } else {
            v
        }
    })
}

/// Install a `[Symbol.iterator]` method on an object that returns `this`.
///
/// Creates a `NativeFunc` unified object wrapping [`native_return_this`] and
/// stores it under `PropertyKey::Symbol(SYMBOL_ITERATOR)` on the target object.
/// This is the standard way to make an iterator also an iterable (the
/// IteratorPrototype pattern from the ES spec).
fn install_symbol_iterator_returns_this(obj: u64) {
    let method = TaggedObj::boxed(
        ObjTag::Unified,
        crate::internal_data::UnifiedObject::native_func(native_return_this, 0),
    );
    property::set_prop_by_symbol_key(obj, crate::symbol::SYMBOL_ITERATOR, method);
}

/// Native function implementing `Generator.prototype.next(value)`.
///
/// Reads `this` from `CURRENT_THIS` and dispatches to the generator resume
/// function with `resume_mode = RESUME_NEXT`.
fn native_generator_next(arg: u64) -> u64 {
    let this = CURRENT_THIS.with(|cell| cell.get());
    dispatch_builtins::dispatch_generator_method_with_arg(this, "next", arg)
}

/// Native function implementing `Generator.prototype.return(value)`.
fn native_generator_return(arg: u64) -> u64 {
    let this = CURRENT_THIS.with(|cell| cell.get());
    dispatch_builtins::dispatch_generator_method_with_arg(this, "return", arg)
}

/// Native function implementing `Generator.prototype.throw(exception)`.
fn native_generator_throw(arg: u64) -> u64 {
    let this = CURRENT_THIS.with(|cell| cell.get());
    dispatch_builtins::dispatch_generator_method_with_arg(this, "throw", arg)
}

/// Install `.next`, `.return`, `.throw` methods on a generator object.
///
/// Creates `NativeFunc` wrappers for each method and installs them as
/// string-keyed properties. This makes the methods visible to property
/// lookups (e.g., `typeof gen.next === "function"`).
fn install_generator_methods(obj: u64) {
    let next_fn = TaggedObj::boxed(
        ObjTag::Unified,
        crate::internal_data::UnifiedObject::native_func(native_generator_next, 1),
    );
    let return_fn = TaggedObj::boxed(
        ObjTag::Unified,
        crate::internal_data::UnifiedObject::native_func(native_generator_return, 1),
    );
    let throw_fn = TaggedObj::boxed(
        ObjTag::Unified,
        crate::internal_data::UnifiedObject::native_func(native_generator_throw, 1),
    );

    let next_key = make_rt_string("next".to_string());
    let return_key = make_rt_string("return".to_string());
    let throw_key = make_rt_string("throw".to_string());

    __esc_rt_set_prop(obj, next_key, next_fn);
    __esc_rt_set_prop(obj, return_key, return_fn);
    __esc_rt_set_prop(obj, throw_key, throw_fn);
}

/// Create a generator object from a state object and resume function index.
///
/// The state object holds: `state_index`, `resume_mode`, `sent_value`, params,
/// and live variable slots. The resume function index identifies which compiled
/// function is the state machine.
///
/// Called by the ramp function (generated by the generator transform) to
/// produce the generator object returned to user code.
///
/// Installs `[Symbol.iterator]`, `.next`, `.return`, `.throw` on the generator.
#[unsafe(no_mangle)]
pub extern "C" fn __esc_rt_create_generator(state: u64, resume_func_idx: u64) -> u64 {
    let generator = TaggedObj::boxed(
        ObjTag::Unified,
        crate::internal_data::UnifiedObject::generator(
            ShapeTable::EMPTY_SHAPE,
            state,
            resume_func_idx as u32,
        ),
    );
    // Install [Symbol.iterator] method that returns `this`
    install_symbol_iterator_returns_this(generator);
    // Install .next, .return, .throw methods
    install_generator_methods(generator);
    generator
}

