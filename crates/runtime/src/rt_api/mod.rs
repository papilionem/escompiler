/// Create a RegExp from NaN-boxed pattern and flags strings.
///
/// Returns a NaN-boxed tagged object with `ObjTag::Unified` and
/// `InternalKind::RegExpObj`, or `undefined` if the pattern or flags are invalid.
#[unsafe(no_mangle)]
pub extern "C" fn __esc_rt_create_regexp(pattern: u64, flags: u64) -> u64 {
    let pattern_str = extract_key_string(pattern).unwrap_or_default();
    let flags_str = extract_key_string(flags).unwrap_or_default();
    match crate::regexp_bridge::JsRegExpData::new(&pattern_str, &flags_str) {
        Ok(data) => TaggedObj::boxed(
            ObjTag::Unified,
            crate::internal_data::UnifiedObject::regexp(ShapeTable::EMPTY_SHAPE, Box::new(data)),
        ),
        Err(_) => JsValue::undefined().raw_bits(),
    }
}

/// Test if a RegExp matches an input string. Returns a NaN-boxed boolean.
///
/// The regexp must be a `UnifiedObject` with `InternalKind::RegExpObj`.
#[unsafe(no_mangle)]
pub extern "C" fn __esc_rt_regexp_test(regexp: u64, input: u64) -> u64 {
    let input_str = extract_key_string(input).unwrap_or_default();
    let tag = read_obj_tag(regexp);
    if tag != Some(ObjTag::Unified as u8) {
        return JsValue::bool(false).raw_bits();
    }
    let uni = unsafe {
        // SAFETY: tag check confirms this is a unified object.
        deref_tagged_mut::<crate::internal_data::UnifiedObject>(regexp)
    };
    if let Some(u) = uni
        && let Some(crate::internal_data::InternalData::RegExp { inner }) = u.internal_data_mut()
        && let Some(re) = inner.downcast_mut::<crate::regexp_bridge::JsRegExpData>()
    {
        return JsValue::bool(re.inner.test(&input_str)).raw_bits();
    }
    JsValue::bool(false).raw_bits()
}

/// Execute a RegExp against input. Returns a NaN-boxed array of matches or null.
///
/// The returned array contains `[full_match, ...capture_groups]` and has an
/// `"index"` property set to the match position.
///
/// The regexp must be a `UnifiedObject` with `InternalKind::RegExpObj`.
#[unsafe(no_mangle)]
pub extern "C" fn __esc_rt_regexp_exec(regexp: u64, input: u64) -> u64 {
    let input_str = extract_key_string(input).unwrap_or_default();
    let tag = read_obj_tag(regexp);
    let match_result = if tag == Some(ObjTag::Unified as u8) {
        let uni = unsafe {
            // SAFETY: tag check confirms this is a unified object.
            deref_tagged_mut::<crate::internal_data::UnifiedObject>(regexp)
        };
        if let Some(u) = uni
            && let Some(crate::internal_data::InternalData::RegExp { inner }) =
                u.internal_data_mut()
        {
            inner
                .downcast_mut::<crate::regexp_bridge::JsRegExpData>()
                .and_then(|re| re.inner.exec(&input_str))
        } else {
            None
        }
    } else {
        None
    };

    match match_result {
        Some(m) => {
            // Create array: [full_match, ...groups]
            let arr_bits = __esc_rt_create_array(0);
            // Push full match
            let full_bits = make_rt_string(m.full_match);
            __esc_rt_array_push(arr_bits, full_bits);
            // Push capture groups
            for group in &m.groups {
                match group {
                    Some(s) => {
                        let s_bits = make_rt_string(s.clone());
                        __esc_rt_array_push(arr_bits, s_bits);
                    }
                    None => {
                        __esc_rt_array_push(arr_bits, JsValue::undefined().raw_bits());
                    }
                }
            }
            // Set index property on the result array
            let index_key = make_rt_string("index".to_string());
            let index_val = JsValue::number(m.index as f64).raw_bits();
            __esc_rt_set_prop(arr_bits, index_key, index_val);
            arr_bits
        }
        None => JsValue::null().raw_bits(),
    }
}

/// Get a property from a RegExp object.
///
/// Supports `source`, `flags`, `global`, `ignoreCase`, `multiline`,
/// `dotAll`, `unicode`, `sticky`, and `lastIndex`.
///
/// The object must be a `UnifiedObject` with `InternalKind::RegExpObj`.
pub(crate) fn get_regexp_property(obj: u64, name: &str) -> u64 {
    let tag = read_obj_tag(obj);
    if tag != Some(ObjTag::Unified as u8) {
        return JsValue::undefined().raw_bits();
    }
    let uni = unsafe {
        // SAFETY: tag check confirms this is a unified object.
        deref_tagged::<crate::internal_data::UnifiedObject>(obj)
    };
    if let Some(u) = uni
        && let Some(crate::internal_data::InternalData::RegExp { inner }) = u.internal_data()
        && let Some(re) = inner.downcast_ref::<crate::regexp_bridge::JsRegExpData>()
    {
        return match name {
            "source" => make_rt_string(re.inner.pattern.clone()),
            "flags" => make_rt_string(re.flags_string()),
            "global" => JsValue::bool(re.inner.flags.global).raw_bits(),
            "ignoreCase" => JsValue::bool(re.inner.flags.ignore_case).raw_bits(),
            "multiline" => JsValue::bool(re.inner.flags.multiline).raw_bits(),
            "dotAll" => JsValue::bool(re.inner.flags.dot_all).raw_bits(),
            "unicode" => JsValue::bool(re.inner.flags.unicode).raw_bits(),
            "sticky" => JsValue::bool(re.inner.flags.sticky).raw_bits(),
            "lastIndex" => JsValue::number(re.inner.last_index as f64).raw_bits(),
            _ => JsValue::undefined().raw_bits(),
        };
    }
    JsValue::undefined().raw_bits()
}

