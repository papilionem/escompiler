/// `console.log()` — prints space-separated display values to stdout.
///
/// Outputs via `__esc_host_fd_write(1, ...)` so that I/O flows through the
/// host abstraction layer rather than directly through `println!`.
///
/// # Safety
///
/// `argv` must point to a valid array of `argc` `u64` values, or be null
/// when `argc` is 0. Compiled code guarantees this.
#[unsafe(no_mangle)]
pub extern "C" fn __esc_rt_console_log(argc: u32, argv: *const u64) {
    let parts = collect_display_args(argc, argv);
    let mut output = parts.join(" ");
    output.push('\n');
    write_to_fd(1, &output);
}

/// `console.error()` — prints space-separated display values to stderr.
///
/// Outputs via `__esc_host_fd_write(2, ...)`.
///
/// # Safety
///
/// Same safety requirements as `__esc_rt_console_log`.
#[unsafe(no_mangle)]
pub extern "C" fn __esc_rt_console_error(argc: u32, argv: *const u64) {
    let parts = collect_display_args(argc, argv);
    let mut output = parts.join(" ");
    output.push('\n');
    write_to_fd(2, &output);
}

/// `console.warn()` — prints to stderr (same as `console.error`).
///
/// Outputs via `__esc_host_fd_write(2, ...)`.
///
/// # Safety
///
/// Same safety requirements as `__esc_rt_console_log`.
#[unsafe(no_mangle)]
pub extern "C" fn __esc_rt_console_warn(argc: u32, argv: *const u64) {
    let parts = collect_display_args(argc, argv);
    let mut output = parts.join(" ");
    output.push('\n');
    write_to_fd(2, &output);
}

/// Collects display-formatted strings from a C argument array.
fn collect_display_args(argc: u32, argv: *const u64) -> Vec<String> {
    if argv.is_null() || argc == 0 {
        return vec![];
    }
    let args = unsafe {
        // SAFETY: Caller (compiled code) guarantees argc and argv are valid.
        std::slice::from_raw_parts(argv, argc as usize)
    };
    args.iter()
        .map(|&bits| display::display_value(JsValue::from_raw_bits(bits)))
        .collect()
}

// =========================================================================
// Console object — `console` as a value, not just a call site (R1-05b)
// =========================================================================

thread_local! {
    /// The `console` namespace singleton object.
    ///
    /// `console` is a host-defined object (Node exposes it as `%console%`); it
    /// is an ordinary object so `typeof console` is `"object"`. Its methods
    /// (`log`, `info`, `debug`, `trace`, `error`, `warn`) are real function
    /// values, so `typeof console.error` is `"function"`.
    static CONSOLE_OBJECT: std::cell::Cell<u64> = const { std::cell::Cell::new(0) };
}

/// Native trampoline for a console method that writes to stdout.
///
/// Reads `CURRENT_ARGC` / `CURRENT_ARGV` from thread-locals (set by the
/// dispatch layer before invoking a NativeFunc) and forwards to
/// `__esc_rt_console_log`.
fn console_stdout_trampoline(_context: u64) -> u64 {
    let argc = CURRENT_ARGC.with(|cell| cell.get());
    let argv = CURRENT_ARGV.with(|cell| cell.get());
    __esc_rt_console_log(argc, argv);
    JsValue::undefined().raw_bits()
}

/// Native trampoline for a console method that writes to stderr.
///
/// Same contract as [`console_stdout_trampoline`], but forwards to
/// `__esc_rt_console_error`.
fn console_stderr_trampoline(_context: u64) -> u64 {
    let argc = CURRENT_ARGC.with(|cell| cell.get());
    let argv = CURRENT_ARGV.with(|cell| cell.get());
    __esc_rt_console_error(argc, argv);
    JsValue::undefined().raw_bits()
}

/// Install a console method as a real, readable function-valued property.
///
/// Creates a `NativeFunc` wrapper whose trampoline routes to the matching
/// `__esc_rt_console_*` output function and stores it as an own property of
/// the console object. The `name`/`length`/`__non_ctor__` markers mirror the
/// built-in method wrapping in `property::get_or_create_builtin_method`.
fn install_console_method(obj: u64, name: &str, trampoline: fn(u64) -> u64) {
    let func = crate::internal_data::UnifiedObject::native_func(trampoline, 0);
    let bits = TaggedObj::boxed(ObjTag::Unified, func);
    OBJECT_PROPS.with(|props| {
        let mut props = props.borrow_mut();
        let map = props.entry(bits).or_default();
        map.insert("name".to_string(), make_rt_string(name.to_string()));
        // Console methods are variadic; per the WHATWG console standard their
        // declared arity is 0.
        map.insert("length".to_string(), JsValue::number(0.0).raw_bits());
        // §10.3.2: built-in methods do not implement [[Construct]].
        map.insert("__non_ctor__".to_string(), JsValue::bool(true).raw_bits());
    });
    let key = make_rt_string(name.to_string());
    __esc_rt_set_prop(obj, key, bits);
}

/// Get or lazily create the `console` namespace object.
///
/// The compiler lowers call-position `console.log(...)` straight to the
/// `__esc_rt_console_log` fast path; this entry point exists for every other
/// appearance of `console` — reading it as a value, aliasing its methods
/// (`var f = console.error`), and feature detection
/// (`typeof console !== "undefined"`).
///
/// Returns the singleton `console` object, preserving identity semantics
/// (`console === console`).
#[unsafe(no_mangle)]
pub extern "C" fn __esc_rt_get_console() -> u64 {
    CONSOLE_OBJECT.with(|cell| {
        let cached = cell.get();
        if cached != 0 {
            return cached;
        }
        let obj = __esc_rt_create_object();
        cell.set(obj);

        for name in ["log", "info", "debug", "trace"] {
            install_console_method(obj, name, console_stdout_trampoline);
        }
        for name in ["error", "warn"] {
            install_console_method(obj, name, console_stderr_trampoline);
        }
        obj
    })
}

