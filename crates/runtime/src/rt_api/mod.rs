//! C ABI runtime surface for compiled JavaScript code.
//!
//! All functions in this module are `#[unsafe(no_mangle)] pub extern "C"` with `u64`
//! parameters representing NaN-boxed `JsValue` bits. The compiled code calls
//! these functions via symbol linkage at runtime.
//!
//! Naming convention: `__esc_rt_<category>_<operation>`.
//!
//! This module is organized into submodules by category:
//! - [`property`] — property access (get/set/delete/has)
//! - [`array`] — array creation and `Array.prototype` methods
//! - [`string`] — `String.prototype` and `String` static methods
//! - [`math`] — `Math.*` and `Number.*` static/instance methods
//! - [`object`] — `Object.*` static methods
//! - [`json`] — `JSON.parse` and `JSON.stringify`
//! - [`iterator`] — iterator protocol (`iter_init`, `iter_next`, etc.)
//! - [`conversion`] — type coercions (`ToBoolean`, `ToNumber`, `typeof`, etc.)
//! - [`dispatch_core`] — core call dispatch, constructors, Function.prototype methods
//! - [`dispatch_builtins`] — Promise, Generator, Boolean, Symbol, Date, Object.prototype
//! - [`dispatch_collections`] — Map/Set method dispatch
//! - [`dispatch_regexp`] — RegExp method dispatch

