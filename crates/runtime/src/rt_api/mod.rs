thread_local! {
    /// The current closure environment pointer, set before calling into a
    /// compiled closure body and restored after.
    pub(crate) static CURRENT_CLOSURE_ENV: std::cell::Cell<u64> = const { std::cell::Cell::new(0) };
    /// The current `this` value, set before calling a constructor or method
    /// and restored after.
    pub(crate) static CURRENT_THIS: std::cell::Cell<u64> = const { std::cell::Cell::new(0) };
    /// The current call's argument count, set before dispatch.
    pub static CURRENT_ARGC: std::cell::Cell<u32> = const { std::cell::Cell::new(0) };
    /// The current call's argument vector, set before dispatch.
    pub static CURRENT_ARGV: std::cell::Cell<*const u64> = const { std::cell::Cell::new(std::ptr::null()) };
    /// The current `new.target` value for the active constructor call.
    ///
    /// Set to the constructor function's NaN-boxed bits before calling a
    /// constructor body, and cleared (set to 0 = undefined) after. Regular
    /// (non-construct) calls leave this at 0.
    pub(crate) static CURRENT_NEW_TARGET: std::cell::Cell<u64> = const { std::cell::Cell::new(0) };
    /// The current callee (closure) value, set before calling into a compiled
    /// closure body and restored after. Used by `arguments.callee` in sloppy mode.
    pub(crate) static CURRENT_CALLEE: std::cell::Cell<u64> = const { std::cell::Cell::new(0) };
    /// Flag indicating CURRENT_THIS was explicitly set for the current call
    /// (e.g., by method dispatch or .call/.apply). When false, strict mode
    /// functions should see `this === undefined` instead of the inherited value.
    pub(crate) static THIS_EXPLICITLY_SET: std::cell::Cell<bool> = const { std::cell::Cell::new(false) };
}

/// Get the current closure environment. Called by compiled closure bodies
/// to access their captured variables.
#[unsafe(no_mangle)]
pub extern "C" fn __esc_rt_get_closure_env() -> u64 {
    CURRENT_CLOSURE_ENV.with(|cell| cell.get())
}

/// Collect remaining arguments starting from `start_index` into an array.
///
/// Used by functions with rest parameters (`...rest`). Reads the current
/// call's argc/argv from thread-local storage.
///
/// `start_index_bits` is a NaN-boxed number indicating the parameter index
/// at which rest arguments begin.
#[unsafe(no_mangle)]
pub extern "C" fn __esc_rt_rest_args(start_index_bits: u64) -> u64 {
    let start_index = JsValue::from_raw_bits(start_index_bits)
        .as_number()
        .unwrap_or(0.0) as u32;
    let argc = CURRENT_ARGC.with(|cell| cell.get());
    let argv = CURRENT_ARGV.with(|cell| cell.get());
    if argv.is_null() || start_index >= argc {
        return __esc_rt_create_array(0);
    }
    let mut elements = Vec::new();
    for i in start_index..argc {
        let bits = unsafe {
            // SAFETY: argv points to argc valid u64 values, set by the dispatch caller.
            *argv.add(i as usize)
        };
        elements.push(JsValue::from_raw_bits(bits));
    }
    create_array_from_elements(elements)
}

/// Get the current `this` value. Called by compiled code when encountering
/// `this` expressions.
#[unsafe(no_mangle)]
pub extern "C" fn __esc_rt_this_value() -> u64 {
    CURRENT_THIS.with(|cell| {
        let v = cell.get();
        if v == 0 {
            JsValue::undefined().raw_bits()
        } else {
            v
        }
    })
}

/// Get the current `new.target` value. Called by compiled code when
/// encountering `new.target` meta-property expressions.
///
/// Returns the constructor function when invoked via `new`, or `undefined`
/// when invoked as a regular function call.
#[unsafe(no_mangle)]
pub extern "C" fn __esc_rt_new_target() -> u64 {
    CURRENT_NEW_TARGET.with(|cell| {
        let v = cell.get();
        if v == 0 {
            JsValue::undefined().raw_bits()
        } else {
            v
        }
    })
}

