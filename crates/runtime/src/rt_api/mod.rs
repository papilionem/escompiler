/// `import.meta` — returns an object with `url`, `dirname`, and `filename`.
///
/// When `path_bits` is `0` or `undefined`, returns an empty object (legacy
/// behavior for single-module compilation). When a NaN-boxed string path
/// is provided, populates the `import.meta` properties from that path.
#[unsafe(no_mangle)]
pub extern "C" fn __esc_rt_import_meta(path_bits: u64) -> u64 {
    let obj = __esc_rt_create_object();

    let path_val = JsValue::from_raw_bits(path_bits);
    if path_val.is_undefined() || path_bits == 0 {
        return obj;
    }

    if path_val.is_string() {
        let path_str = string_ops::get_string_data(path_val);
        let path = std::path::Path::new(&path_str);

        // import.meta.url — file:// URL
        let url = format!("file://{path_str}");
        let url_key = make_rt_string("url".to_string());
        let url_val = make_rt_string(url);
        __esc_rt_set_prop(obj, url_key, url_val);

        // import.meta.filename — basename of the module file
        let filename = path
            .file_name()
            .map(|f| f.to_string_lossy().to_string())
            .unwrap_or_default();
        let filename_key = make_rt_string("filename".to_string());
        let filename_val = make_rt_string(filename);
        __esc_rt_set_prop(obj, filename_key, filename_val);

        // import.meta.dirname — directory of the module file
        let dirname = path
            .parent()
            .map(|p| p.to_string_lossy().to_string())
            .unwrap_or_default();
        let dirname_key = make_rt_string("dirname".to_string());
        let dirname_val = make_rt_string(dirname);
        __esc_rt_set_prop(obj, dirname_key, dirname_val);
    }

    obj
}

