/// Install a data property on an ordinary object with `{ [[Writable]]: true,
/// [[Enumerable]]: false, [[Configurable]]: true }` — the standard descriptor
/// for built-in properties per §20 ECMAScript Standard Built-in Objects.
///
/// Used during globalThis initialization to register callable global functions
/// (parseInt, parseFloat, isNaN, etc.) as own non-enumerable data properties.
fn install_global_property(obj: u64, name: &str, value: u64) {
    use crate::internal_data::UnifiedObject;
    use crate::property::DefinePropertyOptions;
    use crate::tagged_obj::deref_tagged_mut;

    let Some(u) = (unsafe { deref_tagged_mut::<UnifiedObject>(obj) }) else {
        return;
    };
    let opts = DefinePropertyOptions {
        value: Some(JsValue::from_raw_bits(value)),
        writable: Some(true),
        enumerable: Some(false),
        configurable: Some(true),
        getter: None,
        setter: None,
    };
    SHAPES.with(|shapes| {
        INTERNER.with(|interner| {
            let mut shapes = shapes.borrow_mut();
            let interner = interner.borrow_mut();
            let _ = u.define_own_property(name, &opts, &mut shapes, &interner);
        });
    });
}

/// Get or lazily initialize the `globalThis` object.
///
/// Returns a plain object that serves as the global `this` value
/// in sloppy mode function calls. On first initialization, installs
/// standard callable global functions (parseInt, parseFloat, isNaN,
/// isFinite, encodeURI, decodeURI, encodeURIComponent, decodeURIComponent)
/// as own data properties per §19.2 of the ES2024 spec, with the standard
/// built-in descriptor attributes `{ [[Writable]]: true, [[Enumerable]]: false,
/// [[Configurable]]: true }`.
///
/// [spec]: https://tc39.es/ecma262/#sec-setdefaultglobalbindings
#[unsafe(no_mangle)]
pub extern "C" fn __esc_rt_get_global_this() -> u64 {
    GLOBAL_THIS.with(|cell| {
        let bits = cell.get();
        if bits == 0 {
            let obj = __esc_rt_create_object();
            cell.set(obj);
            // §19.2 Install callable global function properties on the global object.
            // Each has attributes { [[Writable]]: true, [[Enumerable]]: false,
            // [[Configurable]]: true } per §20 ECMAScript Standard Built-in Objects.
            let callable_globals = [
                "parseInt",
                "parseFloat",
                "isNaN",
                "isFinite",
                "encodeURI",
                "decodeURI",
                "encodeURIComponent",
                "decodeURIComponent",
            ];
            for name in &callable_globals {
                let fn_bits = globals::get_global_object(name);
                if fn_bits != JsValue::undefined().raw_bits() {
                    // Install as own data property with { w:true, e:false, c:true }.
                    install_global_property(obj, name, fn_bits);
                }
            }
            obj
        } else {
            bits
        }
    })
}

