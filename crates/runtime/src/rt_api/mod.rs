use crate::esc_environment::EscEnvironment;
use std::sync::Arc;

/// Convert an `Arc<EscEnvironment>` to NaN-boxed bits for passing through the ABI.
///
/// Increments the Arc's reference count (via `into_raw`) so the environment
/// stays alive.
fn esc_env_to_bits(arc: Arc<EscEnvironment>) -> u64 {
    let ptr = Arc::into_raw(arc) as *const ();
    JsValue::object(ptr).raw_bits()
}

/// Reconstruct an `Arc<EscEnvironment>` from NaN-boxed bits (takes ownership).
///
/// The caller is responsible for ensuring the bits came from `esc_env_to_bits`.
/// This decrements the Arc refcount when the returned Arc is dropped.
fn esc_env_from_bits(bits: u64) -> Arc<EscEnvironment> {
    let v = JsValue::from_raw_bits(bits);
    let ptr = v.as_object().unwrap_or(std::ptr::null());
    assert!(!ptr.is_null(), "BUG: null pointer in esc_env_from_bits");
    unsafe {
        // SAFETY: ptr was created by Arc::into_raw via esc_env_to_bits.
        // We increment the refcount so we don't consume the original.
        Arc::increment_strong_count(ptr as *const EscEnvironment);
        Arc::from_raw(ptr as *const EscEnvironment)
    }
}

/// Reconstruct an `Arc<EscEnvironment>` without incrementing refcount.
///
/// Used for temporary mutable access patterns where we `forget` the Arc afterward.
fn esc_env_arc_from_bits(bits: u64) -> Arc<EscEnvironment> {
    let v = JsValue::from_raw_bits(bits);
    let ptr = v.as_object().unwrap_or(std::ptr::null());
    assert!(!ptr.is_null(), "BUG: null pointer in esc_env_arc_from_bits");
    unsafe {
        // SAFETY: ptr was created by Arc::into_raw via esc_env_to_bits.
        // Caller MUST forget this Arc to avoid double-free.
        Arc::from_raw(ptr as *const EscEnvironment)
    }
}

