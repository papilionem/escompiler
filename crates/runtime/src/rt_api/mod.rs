/// Get the length of a NaN-boxed string value.
#[unsafe(no_mangle)]
pub extern "C" fn __esc_rt_string_length(s: u64) -> u64 {
    let v = JsValue::from_raw_bits(s);
    if v.is_string() {
        let data = string_ops::get_string_data(v);
        JsValue::int(data.len() as i32).raw_bits()
    } else {
        JsValue::int(0).raw_bits()
    }
}

/// Get the character at a given index of a NaN-boxed string.
#[unsafe(no_mangle)]
pub extern "C" fn __esc_rt_string_char_at(s: u64, idx: u64) -> u64 {
    let sv = JsValue::from_raw_bits(s);
    let iv = JsValue::from_raw_bits(idx);
    if sv.is_string() {
        let data = string_ops::get_string_data(sv);
        let i = iv
            .as_int()
            .map(|n| n as usize)
            .or_else(|| iv.as_number().map(|n| n as usize))
            .unwrap_or(0);
        if i < data.len() {
            let ch = &data[i..i + 1];
            make_rt_string(ch.to_string())
        } else {
            make_rt_string(String::new())
        }
    } else {
        make_rt_string(String::new())
    }
}

/// Compare two NaN-boxed string values. Returns <0, 0, or >0.
#[unsafe(no_mangle)]
pub extern "C" fn __esc_rt_string_compare(a: u64, b: u64) -> u64 {
    let av = JsValue::from_raw_bits(a);
    let bv = JsValue::from_raw_bits(b);
    let sa = if av.is_string() {
        string_ops::get_string_data(av)
    } else {
        display::display_value(av)
    };
    let sb = if bv.is_string() {
        string_ops::get_string_data(bv)
    } else {
        display::display_value(bv)
    };
    let result = sa.cmp(&sb) as i32;
    JsValue::int(result).raw_bits()
}

/// Convert a NaN-boxed JS value to an `i32` using ECMAScript `ToInt32`.
fn js_to_int32(bits: u64) -> i32 {
    let n = value_ops::to_number(JsValue::from_raw_bits(bits));
    if n.is_nan() || n.is_infinite() || n == 0.0 {
        return 0;
    }
    let int_val = (n.signum() * n.abs().floor()) as i64;
    ((int_val as u64) % (1u64 << 32)) as u32 as i32
}

/// Convert a NaN-boxed JS value to a `u32` using ECMAScript `ToUint32`.
fn js_to_uint32(bits: u64) -> u32 {
    let n = value_ops::to_number(JsValue::from_raw_bits(bits));
    if n.is_nan() || n.is_infinite() || n == 0.0 {
        return 0;
    }
    let int_val = (n.signum() * n.abs().floor()) as i64;
    ((int_val as u64) % (1u64 << 32)) as u32
}

/// Bitwise AND of two NaN-boxed values.
#[unsafe(no_mangle)]
pub extern "C" fn __esc_rt_bitwise_and(a: u64, b: u64) -> u64 {
    let av = js_to_int32(a);
    let bv = js_to_int32(b);
    JsValue::int(av & bv).raw_bits()
}

