/// Extract a u32 from a NaN-boxed value that may be an i32 or an f64.
///
/// Handles both `JsValue::int(n)` and `JsValue::number(n)` encodings.
fn nanboxed_to_u32(bits: u64) -> u32 {
    let v = JsValue::from_raw_bits(bits);
    if let Some(n) = v.as_int() {
        n as u32
    } else if let Some(n) = v.as_number() {
        n as u32
    } else {
        0
    }
}

/// Callback type for the direct eval implementation.
///
/// Signature: `(code: &str, lex_env: u64, var_env: u64, this_value: u64, is_strict: bool) -> u64`.
/// Registered by the `eval` crate at initialization time to break the circular
/// dependency between `runtime` and `eval`.
pub type EvalDirectFn = fn(&str, u64, u64, u64, bool) -> u64;

/// Global callback for the direct eval implementation.
///
/// Set by [`register_eval_direct`] at initialization time. When `None`, direct
/// eval returns `undefined` (graceful degradation).
static EVAL_DIRECT_CALLBACK: std::sync::OnceLock<EvalDirectFn> = std::sync::OnceLock::new();

/// Register the direct eval implementation callback.
///
/// Called by the `eval` crate during initialization to wire up the self-hosted
/// eval pipeline (oxc -> IR -> Cranelift JIT) without creating a circular
/// dependency.
pub fn register_eval_direct(callback: EvalDirectFn) {
    let _ = EVAL_DIRECT_CALLBACK.set(callback);
}

/// Callback type for the `Function()` constructor implementation.
///
/// Signature: `(params: &[&str], body: &str) -> Result<u64, String>`.
/// The callback receives the parsed parameter strings and body, JIT-compiles
/// them into a function, and returns the function object bits. On parse/compile
/// failure it returns `Err(message)` for a SyntaxError.
///
/// Registered by the `eval` crate at initialization time to break the circular
/// dependency between `runtime` and `eval`.
pub type FunctionConstructorFn = fn(&[&str], &str) -> Result<u64, String>;

/// Global callback for the `Function()` constructor implementation.
///
/// Set by [`register_function_constructor`] at initialization time. When `None`,
/// `new Function(...)` returns an empty function object (graceful degradation).
static FUNCTION_CTOR_CALLBACK: std::sync::OnceLock<FunctionConstructorFn> =
    std::sync::OnceLock::new();

/// Register the `Function()` constructor implementation callback.
///
/// Called by the `eval` crate during initialization to wire up the self-hosted
/// Function constructor pipeline (oxc -> IR -> Cranelift JIT) without creating
/// a circular dependency.
pub fn register_function_constructor(callback: FunctionConstructorFn) {
    let _ = FUNCTION_CTOR_CALLBACK.set(callback);
}

/// `Function()` constructor: creates a new function from strings at runtime.
///
/// ABI: `(argc: u32, argv: *const u64) -> u64`.
/// `argv` contains the NaN-boxed string arguments. The last argument is the body;
/// all preceding arguments are parameter names (possibly comma-separated).
///
/// Per ES spec:
/// - `Function("a", "b", "return a + b")` — multiple param strings
/// - `Function("a,b", "return a + b")` — comma-separated in one string
/// - `Function("return 42")` — no params, just body
/// - Calling without `new` works identically to `new Function(...)`
/// - The created function has global scope (not caller's scope)
/// - The function name is "anonymous"
/// - If parsing fails, throws SyntaxError
///
/// # Safety
///
/// `argv` must point to `argc` valid u64 values, or be null when `argc` is 0.
pub unsafe fn construct_function(argc: u32, argv: *const u64) -> u64 {
    // Collect string arguments
    let mut string_args: Vec<String> = Vec::with_capacity(argc as usize);
    for i in 0..argc as usize {
        let bits = if !argv.is_null() {
            // SAFETY: i < argc, and argv has argc valid elements per caller contract.
            unsafe { *argv.add(i) }
        } else {
            JsValue::undefined().raw_bits()
        };
        let val = JsValue::from_raw_bits(bits);
        if val.is_string() {
            string_args.push(string_ops::get_string_data(val));
        } else if val.is_undefined() {
            string_args.push(String::new());
        } else {
            // Convert to string per spec
            let s_bits = __esc_rt_to_string(bits);
            let s_val = JsValue::from_raw_bits(s_bits);
            string_args.push(string_ops::get_string_data(s_val));
        }
    }

    // Split into params and body per ES spec:
    // - If no args: params = [], body = ""
    // - If one arg: params = [], body = args[0]
    // - If 2+ args: params = args[0..n-1] (joined with ","), body = args[n-1]
    let (param_strings, body) = if string_args.is_empty() {
        (Vec::new(), String::new())
    } else if string_args.len() == 1 {
        (
            Vec::new(),
            string_args.into_iter().next().unwrap_or_default(),
        )
    } else {
        let body = string_args.last().cloned().unwrap_or_default();
        let params = string_args[..string_args.len() - 1].to_vec();
        (params, body)
    };

    // Flatten comma-separated params: "a,b" -> ["a", "b"]
    let flat_params: Vec<String> = param_strings
        .iter()
        .flat_map(|p| p.split(',').map(|s| s.trim().to_string()))
        .filter(|s| !s.is_empty())
        .collect();

    let param_refs: Vec<&str> = flat_params.iter().map(|s| s.as_str()).collect();

    // Call through the registered callback if available
    if let Some(ctor_fn) = FUNCTION_CTOR_CALLBACK.get() {
        match ctor_fn(&param_refs, &body) {
            Ok(func_bits) => func_bits,
            Err(msg) => {
                // Throw SyntaxError
                let err_msg = make_rt_string(msg);
                let err = __esc_rt_create_error(exceptions::error_tag::SYNTAX_ERROR, err_msg);
                __esc_rt_throw(err);
                JsValue::undefined().raw_bits()
            }
        }
    } else {
        // No callback registered — return a plain empty function object
        JsValue::undefined().raw_bits()
    }
}

/// Direct eval with scope bridging.
///
/// ABI matches `get_call_variadic`: `(code: u64, argc: u32, argv: *const u64) -> u64`.
/// The `code` parameter is the NaN-boxed source string to evaluate.
/// The `argv` array contains `[lex_env, var_env, this_value]` (argc = 3).
///
/// If the eval callback has not been registered, returns `undefined`.
#[unsafe(no_mangle)]
pub extern "C" fn __esc_rt_call_eval_direct(code: u64, argc: u32, argv: *const u64) -> u64 {
    // Extract the code string from the NaN-boxed value
    let code_val = JsValue::from_raw_bits(code);
    if !code_val.is_string() {
        // Per ES spec: if the argument to eval is not a string, return it directly
        return code;
    }
    let code_str = string_ops::get_string_data(code_val);

    // Extract lex_env, var_env, this_value from argv
    let (lex_env, var_env, this_value) = extract_eval_args(argc, argv);

    // Detect strict mode from the source (simple "use strict" directive check)
    let is_strict = detect_strict_mode(&code_str);

    // Call through the registered callback if available
    if let Some(eval_fn) = EVAL_DIRECT_CALLBACK.get() {
        eval_fn(&code_str, lex_env, var_env, this_value, is_strict)
    } else {
        // No eval callback registered — return undefined
        JsValue::undefined().raw_bits()
    }
}

/// Detect whether a source string begins with a `"use strict"` directive.
///
/// Checks for `"use strict"` or `'use strict'` at the start of the source,
/// ignoring leading whitespace and comments.
fn detect_strict_mode(source: &str) -> bool {
    let trimmed = source.trim_start();
    trimmed.starts_with("\"use strict\"") || trimmed.starts_with("'use strict'")
}

/// Extract eval arguments from the variadic argv array.
///
/// Returns `(lex_env, var_env, this_value)` from the argv, or undefined values
/// if argc is less than 3 or argv is null.
///
/// # Safety
///
/// `argv` must point to at least `argc` consecutive `u64` values, or be null.
fn extract_eval_args(argc: u32, argv: *const u64) -> (u64, u64, u64) {
    if argc >= 3 && !argv.is_null() {
        unsafe {
            // SAFETY: argv was constructed by the Cranelift codegen with at least
            // `argc` entries, each being a u64 NaN-boxed value.
            let lex = *argv;
            let var = *argv.add(1);
            let this = *argv.add(2);
            (lex, var, this)
        }
    } else {
        (
            JsValue::undefined().raw_bits(),
            JsValue::undefined().raw_bits(),
            JsValue::undefined().raw_bits(),
        )
    }
}

